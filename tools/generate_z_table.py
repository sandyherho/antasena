"""Regenerate ``src/antasena/eos/_zdata.py`` from the reference mixture EOS.

Run once by maintainers; antasena itself never imports CoolProp.

The compressibility factor Z(T, P, x_O2) of the binary O2/N2 system is
evaluated with the Helmholtz-energy mixture model implemented in CoolProp
(HEOS backend, Kunz-Wagner/GERG-type mixing of the reference pure-fluid
equations of state for nitrogen and oxygen). Argon in atmospheric air is
lumped with nitrogen, which shifts Z by less than about 0.15 % at 300 bar.

Usage::

    python tools/generate_z_table.py            # writes the data module
    python tools/generate_z_table.py --check    # writes off-grid check points
"""
from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

import CoolProp
import CoolProp.CoolProp as CP

ROOT = Path(__file__).resolve().parents[1]
T_GRID = [253.15 + 5.0 * i for i in range(21)]          # 253.15 ... 353.15 K
P_GRID = [10.0 * i for i in range(41)]                  # 0 ... 400 bar
X_GRID = [round(0.05 * i, 2) for i in range(21)]        # x_O2 = 0 ... 1


def z_ref(T: float, p_bar: float, x_o2: float) -> float:
    if p_bar == 0.0:
        return 1.0
    if x_o2 <= 0.0:
        fluid = "HEOS::Nitrogen"
    elif x_o2 >= 1.0:
        fluid = "HEOS::Oxygen"
    else:
        fluid = f"HEOS::Nitrogen[{1.0 - x_o2!r}]&Oxygen[{x_o2!r}]"
    return CP.PropsSI("Z", "T", T, "P", p_bar * 1e5, fluid)


def write_table() -> None:
    values = []
    for x in X_GRID:
        for T in T_GRID:
            for p in P_GRID:
                values.append(round(z_ref(T, p, x), 7))
    out = ROOT / "src" / "antasena" / "eos" / "_zdata.py"
    with out.open("w") as fh:
        fh.write('"""Tabulated reference compressibility factor Z(T, P, x_O2).\n\n')
        fh.write("Generated by tools/generate_z_table.py with CoolProp "
                 f"{CoolProp.__version__} (HEOS mixture model). Do not edit.\n")
        fh.write('Index order: Z[(ix * NT + iT) * NP + iP].\n"""\n\n')
        fh.write(f"COOLPROP_VERSION = {CoolProp.__version__!r}\n")
        fh.write(f"T_MIN, T_STEP, NT = 253.15, 5.0, {len(T_GRID)}\n")
        fh.write(f"P_MIN, P_STEP, NP = 0.0, 10.0, {len(P_GRID)}\n")
        fh.write(f"X_MIN, X_STEP, NX = 0.0, 0.05, {len(X_GRID)}\n")
        fh.write("Z = (\n")
        for i in range(0, len(values), 8):
            fh.write("    " + ", ".join(f"{v:.7f}" for v in values[i:i + 8]) + ",\n")
        fh.write(")\n")
    print(f"wrote {out} ({len(values)} values)")


def write_check_points(n: int = 400, seed: int = 20261015) -> None:
    rng = random.Random(seed)
    pts = []
    for _ in range(n):
        T = rng.uniform(258.15, 348.15)
        p = rng.uniform(1.0, 395.0)
        x = rng.uniform(0.0, 1.0)
        pts.append([T, p, x, z_ref(T, p, x)])
    out = ROOT / "tests" / "data" / "z_reference_checkpoints.json"
    out.write_text(json.dumps({"coolprop_version": CoolProp.__version__,
                               "seed": seed, "points": pts}, indent=1))
    print(f"wrote {out}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    write_check_points() if a.check else write_table()
